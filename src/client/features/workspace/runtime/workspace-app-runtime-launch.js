      hideAICoreWorkspace: aiCoreWorkspaceRuntime.hideAICoreWorkspace,
      deleteSelectedNode: canvasSelectionRuntime.deleteSelectedNode,
      selectNode: canvasSelectionRuntime.selectNode,
      panForZoomAroundWorldPoint,
      showCanvasContextMenu: canvasInteractionRuntime.showCanvasContextMenu,
      hideImageEditPopover: canvasInteractionRuntime.hideImageEditPopover,
      addCanvasToolNode: canvasOperationsRuntime.addCanvasToolNode,
      createDrawingPreview: canvasOperationsRuntime.createDrawingPreview,
      updateDrawingPreview: canvasOperationsRuntime.updateDrawingPreview,
      finishCanvasDrawing: canvasOperationsRuntime.finishCanvasDrawing,
      startEraserDrag: canvasOperationsRuntime.startEraserDrag,
      updateEraserDrag: canvasOperationsRuntime.updateEraserDrag,
      finishEraserDrag: canvasOperationsRuntime.finishEraserDrag,
      createSelectionBox: canvasOperationsRuntime.createSelectionBox,
      updateSelectionBox: canvasOperationsRuntime.updateSelectionBox,
      finishSelectionBox: canvasOperationsRuntime.finishSelectionBox,
      showView: projectHomeRuntime.showView,
      fitWorldBoundsInViewport,
      clampCanvasZoom,
      getVisibleCanvasNodes,
      getNodeBounds,
      refreshDirectorOptions: canvasGenerationRuntime.refreshDirectorOptions,
      runDirectorAction,
      getAddMenuPoint: canvasInteractionRuntime.getAddMenuPoint,
      setAddMenuPoint: canvasInteractionRuntime.setAddMenuPoint,
      getContextMenuPoint: canvasInteractionRuntime.getContextMenuPoint,
      getContextMenuTargetNode: canvasInteractionRuntime.getContextMenuTargetNode,
      setContextMenuPoint: canvasInteractionRuntime.setContextMenuPoint,
      viewportPointToWorld: canvasInteractionRuntime.viewportPointToWorld,
