      saveCurrentProject: projectHomeRuntime.saveCurrentProject,
      makeProjectTitle: projectHomeRuntime.makeProjectTitle,
      postJsonRequest,
      buildChatImagePayload,
      readFileAsDataUrl,
      detectGenerationKind,
      getPendingHomeGenerationFocus,
      setPendingHomeGenerationFocus,
      centerViewOnNode,
      chooseUploadMode: canvasGenerationRuntime.chooseUploadMode,
      getPendingUploadChoice: canvasGenerationRuntime.getPendingUploadChoice,
      setPendingUploadChoice: canvasGenerationRuntime.setPendingUploadChoice,
