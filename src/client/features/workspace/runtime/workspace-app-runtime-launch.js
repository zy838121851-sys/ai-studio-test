      runImageEditCommand,
      handleImageEditSubmit: canvasInteractionRuntime.handleImageEditSubmit,
      handleImageEditCancel: canvasInteractionRuntime.handleImageEditCancel,
      renderHomeHistory: projectHomeRuntime.renderHomeHistory,
      renderAssets: assetRuntime.renderAssets,
      getActiveProject: projectHomeRuntime.getActiveProject,
      updateProjectTitle: projectHomeRuntime.updateProjectTitle,
      runCanvasTool: canvasOperationsRuntime.runCanvasTool,
      setShapeTool: canvasOperationsRuntime.setShapeTool,
      applyTextStyle: canvasInteractionRuntime.applyTextStyle,
      toggleToolRailCollapsed,
      renderHomeFilePreview: projectHomeRuntime.renderHomeFilePreview,
      setHomeFiles: projectHomeRuntime.setHomeFiles,
      openHomeFilePicker: projectHomeRuntime.openHomeFilePicker,
      setLibraryViewModeStorage: setLibraryViewMode,
      renderProjectLibrary: projectHomeRuntime.renderProjectLibrary,
      selectLibraryProject: projectHomeRuntime.selectLibraryProject,
      stepLibraryProject: projectHomeRuntime.stepLibraryProject,
      openProject: projectHomeRuntime.openProject,
      deleteProject: projectHomeRuntime.deleteProject,
      newBlankProject: projectHomeRuntime.newBlankProject,
      saveCurrentProject: projectHomeRuntime.saveCurrentProject,
      generateHomeProject: projectHomeRuntime.generateHomeProject,
      addChatImageFiles: canvasGenerationRuntime.addChatImageFiles,
      recordCanvasEvent,
      commitProjectTitleEdit: projectHomeRuntime.commitProjectTitleEdit,
      addThinking: chatRuntime.addThinking,
      updateThinking: chatRuntime.updateThinking,
