      setUploadModeHover: canvasGenerationRuntime.setUploadModeHover,
      setAICoreState,
      isPointInAICore,
      updateAICoreDragState,
      uploadIntoAICore: aiCoreWorkspaceRuntime.uploadIntoAICore,
